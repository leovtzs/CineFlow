
package br.edu.ifba.streaming.usuario;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;

public class ConexaoBanco {

    private static final String URL =
            "jdbc:h2:./data/cineflow;LOCK_TIMEOUT=5000";

    private static final String USUARIO = "sa";
    private static final String SENHA = "";

    public static Connection conectar() throws SQLException {
        System.out.println("[BANCO] Tentando abrir conexão H2...");

        Connection conexao = DriverManager.getConnection(
                URL, USUARIO, SENHA
        );

        System.out.println("[BANCO] Conexão H2 aberta.");
        return conexao;
    }

    public static void criarTabela() {
        String sql = """
                CREATE TABLE IF NOT EXISTS usuarios (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    nome VARCHAR(100) NOT NULL,
                    email VARCHAR(150) NOT NULL UNIQUE,
                    senha_hash VARCHAR(255) NOT NULL
                )
                """;

        try (Connection conexao = conectar();
             Statement comando = conexao.createStatement()) {

            comando.execute(sql);
            String sqlAssistirDepois = """
        CREATE TABLE IF NOT EXISTS assistir_depois (
            usuario_id INTEGER NOT NULL,
            conteudo_id INTEGER NOT NULL,
            PRIMARY KEY (usuario_id, conteudo_id),
            FOREIGN KEY (usuario_id)
                REFERENCES usuarios(id)
                ON DELETE CASCADE
        )
        """;

comando.execute(sqlAssistirDepois);

System.out.println(
        "[BANCO] Tabela assistir_depois preparada!"
);
            System.out.println("[BANCO] Tabela de usuários preparada!");

        } catch (SQLException e) {
            System.err.println("[BANCO] Erro ao preparar banco:");
            e.printStackTrace();
        }
    }
}
